import fs from 'node:fs';
import path from 'node:path';

function stripImportsAndExports(code) {
  return code
    // Remove import statements (single and multi-line)
    .replace(/^import\s+[\s\S]*?from\s+['"][^'"]+['"];?\s*$/gm, '')
    .replace(/^import\s+['"][^'"]+['"];?\s*$/gm, '')
    // Remove export keywords from declarations
    .replace(/^export\s+(async\s+function|function|const|let|var)\s+/gm, '$1 ')
    // Remove export { ... } blocks
    .replace(/^export\s*\{[\s\S]*?\};?\s*$/gm, '')
    // Remove export default
    .replace(/^export\s+default\s+[\s\S]*?;?\s*$/gm, '')
    .trim();
}

const htmlToTextPath = path.resolve('extension/src/lib/html-to-text.js');
const urlUtilsPath = path.resolve('extension/src/lib/url-utils.js');
const extractorSrcPath = path.resolve('extension/src/content/extractor-src.js');
const extractorOutputPath = path.resolve('extension/src/content/extractor.js');

const defaultResumePath = path.resolve('extension/src/lib/default-resume.js');
const bridgeSrcPath = path.resolve('extension/src/content/hiregram-bridge-src.js');
const bridgeOutputPath = path.resolve('extension/src/content/hiregram-bridge.js');

const htmlToTextCode = stripImportsAndExports(fs.readFileSync(htmlToTextPath, 'utf8'));
const urlUtilsCode = stripImportsAndExports(fs.readFileSync(urlUtilsPath, 'utf8'));
const extractorSrcCode = stripImportsAndExports(fs.readFileSync(extractorSrcPath, 'utf8'));

const defaultResumeCode = stripImportsAndExports(fs.readFileSync(defaultResumePath, 'utf8'));
const bridgeSrcCode = stripImportsAndExports(fs.readFileSync(bridgeSrcPath, 'utf8'));

// 1. Build self-contained IIFE classic extractor script
const bundledExtractor = `/**
 * Job Context Extractor
 * Self-contained classic content script (IIFE) for chrome.scripting.executeScript.
 * Generated by scripts/build-content.mjs — DO NOT EDIT DIRECTLY.
 * Source: src/lib/html-to-text.js, src/lib/url-utils.js, src/content/extractor-src.js
 */
(() => {
  // === Inlined from src/lib/html-to-text.js ===
  ${htmlToTextCode}

  // === Inlined from src/lib/url-utils.js ===
  ${urlUtilsCode}

  // === Extractor Logic ===
  ${extractorSrcCode}

  if (typeof document !== 'undefined' && typeof window !== 'undefined') {
    return extractJobContextFromDocument(document, window);
  }
  return null;
})();
`;

// Validation: Ensure absolutely no import or export statements exist in the classic script
const importMatch1 = bundledExtractor.match(/\bimport\s+[\s\S]*?from\s+['"]|\bimport\s*\(|\bexport\s+/);
if (importMatch1) {
  throw new Error(`Build validation failed: extractor script contains forbidden keyword "${importMatch1[0]}"`);
}

fs.writeFileSync(extractorOutputPath, bundledExtractor, 'utf8');
console.log(`Generated self-contained content script: ${extractorOutputPath} (${bundledExtractor.length} bytes)`);

// 2. Build self-contained IIFE classic bridge script
const bundledBridge = `/**
 * Hiregram Bridge Content Script (Self-contained classic script)
 * Runs on https://hiregram.ai/* and https://www.hiregram.ai/*
 * Generated by scripts/build-content.mjs — DO NOT EDIT DIRECTLY.
 * Source: src/lib/default-resume.js, src/content/hiregram-bridge-src.js
 */
// === Inlined from src/lib/default-resume.js ===
${defaultResumeCode}

// === Bridge Logic ===
${bridgeSrcCode}
`;

const importMatch2 = bundledBridge.match(/\bimport\s+[\s\S]*?from\s+['"]|\bimport\s*\(|\bexport\s+/);
if (importMatch2) {
  throw new Error(`Build validation failed: bridge script contains forbidden keyword "${importMatch2[0]}"`);
}

fs.writeFileSync(bridgeOutputPath, bundledBridge, 'utf8');
console.log(`Generated self-contained content script: ${bridgeOutputPath} (${bundledBridge.length} bytes)`);
